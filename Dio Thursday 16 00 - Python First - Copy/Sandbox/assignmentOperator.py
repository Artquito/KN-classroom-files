num1 = 20
num2 = 5

print(f"First number: {num1}")
print(f"Second number: {num2}")

num1 = num1 + num2
print(f"num1 + num2 is equals to {num1}")
print(f"The current value of num1 is {num1}")

num1 += num2 #shorthand
print(f"num1 += num2 is equals to {num1}")
print(f"The current value of num1 is {num1}")

num1 -= num2
print(f"num1 -= num2 is equals to {num1}")
print(f"The current value of num1 is {num1}")

num1 *= num2 # multiplication
print(f"num1  num2 is equals to {num1}")
print(f"The current value of num1 is {num1}")

num1 /= num2 # division
print(f"num1  num2 is equals to {num1}")
print(f"The current value of num1 is {num1}")