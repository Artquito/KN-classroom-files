num1 = 5
num2 = 5

print(f'First number: {num1}') # 5
print(f'Second number: {num2}') # 5

print(f'The statement of {num1} > {num2} is {num1 > num2}.') # False
print(f'The statement of {num1} < {num2} is {num1 < num2}.') # False
print(f'The statement of {num1} >= {num2} is {num1 >= num2}.') # True
print(f'The statement of {num1} <= {num2} is {num1 <= num2}.') # True
print(f'The statement of {num1} == {num2} is {num1 == num2}.') # True